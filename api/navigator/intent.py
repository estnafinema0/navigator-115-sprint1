"""Граница 115-ФЗ на входе: распознать запрос на обход контроля и ответить отказом по шаблону.

PROMPT.md, разд. 1.3: продукт никогда не советует, как обойти контроль, не переформулирует
назначение платежа, не сочиняет экономический смысл операций и не обещает разблокировку.
Детерминированные правила, без LLM: решение объяснимо и одинаково для любого входа.
Срабатывание на текст банка (инъекция в загруженном документе) тоже фиксируется: такой текст
разбирается как обычно, но инструкции из него не исполняются — LLM только извлекает поля с цитатой.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

F = re.IGNORECASE | re.UNICODE

# Глаголы правки назначения платежа. «Измени/поменяй/замени» — только в повелительной форме (просьба к сервису):
# «поменялось назначение после смены договора» и «можно ли изменить назначение» — обычные вопросы.
# «Исправить ошибку в назначении» — законное уточнение платежа, не обход (протокол красной команды 27.10).
_PURPOSE_VERBS = (r"(?:переформулир\w*|перепиш\w*|перепис\w*|подправ\w*|придума\w*|подбер\w*|подобра\w*|"
                  r"сформулируй\w*|измени(?:те)?\b|поменяй\w*|замени(?:те)?\b)")
_EVADE_OBJ = r"(?:заблок|блокир|вопрос|проверк|пропуст|придир|финмон|заметил|триггер)"

BYPASS_PATTERNS: list[tuple[str, re.Pattern]] = [
    ("rewrite_purpose", re.compile(
        _PURPOSE_VERBS + r"[^.?!]{0,40}назначени\w*\s+(?:платеж|платёж)|"
        r"назначени\w*(?:\s+(?:платеж|платёж)\w*)?[^.?!]{0,40}(?:чтобы|так,\s+чтобы)[^.?!]{0,40}(?:не\s+)?" + _EVADE_OBJ, F)),
    ("invent_explanation", re.compile(
        r"(?:придума|сочини|выдума)\w*[^.?!]{0,50}(?:легенд|экономическ\w+\s+смысл|обоснован|пояснени|объяснени)|"
        r"(?:составь|состав|напиши|написа|сгенерир|сформулир)\w*[^.?!]{0,50}(?:легенд|экономическ|обоснован|пояснени|объяснени)\w*"
        r"[^.?!]{0,60}(?:котор\w+[^.?!]{0,20}(?:не\s+было|нет)|чтобы\s+(?:банк\s+)?(?:поверил|принял|разблокировал|отстал|не\s+придрал)|правдоподобн|убедительн)|"
        r"(?:правдоподобн|убедительн)\w*\s+(?:легенд|пояснени|объяснени|обоснован)\w*|легенд\w*\s+(?:для|банку)|"
        r"(?:сформулируй|сформулируйте|сочини|придумай|напиши|напишите|составь|составьте|опиши|опишите)\s+(?:\w+\s+){0,2}экономическ\w+\s+смысл|"
        r"(?:перепиши|перепишите|переформулируй|улучши|подправь|приукрась)\w*\s+(?:\w+\s+){0,2}(?:пояснени|объяснени|ответ|обоснован|письм)\w*"
        r"[^.?!]{0,40}(?:убедительн|правдоподобн|чтобы)", F)),
    ("split_payments", re.compile(
        r"(?:разб|раздел|дроб)\w*\s+(?:\w+\s+){0,2}(?:платеж|платёж|сумм|перевод|операци)\w*|"
        r"(?:какими|на\s+какие)\s+суммами\s+(?:перевод|плат|снима)\w*[^.?!]{0,40}(?:чтобы|не\s+)|"
        r"частями\s+по\s+\d+\s*(?:тыс|000|к\b|т\.|млн)|"
        r"(?:переводи|перевести|снима|снять|вноси|внести|кида|закину)\w*\s+(?:\w+\s+){0,3}частями", F)),
    ("evade_control", re.compile(
        r"(?:как|чтобы|способ\w*)\s+(?:\w+\s+){0,3}(?:обойти|обхода|не\s+попасть\s+под|избежать)\s+(?:\w+\s+){0,2}(?:контрол|проверк|115|161|блокировк|финмониторинг|комплаенс)\w*|"
        r"чтобы\s+(?:банк\s+)?не\s+(?:заметил|увидел|узнал|спросил|проверял)|"
        r"(?:обналич|вывести\s+(?:деньги|средства)\s+(?:через|на)\s+(?:чуж|друг|родствен|подставн))\w*|"
        r"(?:на\s+чей|через\s+чей|через\s+(?:родствен|друз|знаком)\w*)\s+(?:\w+\s+)?(?:счёт|счет|карт)\w*\s+(?:провести|прогнать|пропустить)|"
        r"(?:слов|фраз|формулировк)\w*[^.?!]{0,30}(?:тригер|триггер)\w*|"
        r"(?:тригер|триггер)\w*\s+(?:\w+\s+)?(?:финмониторинг|антифрод|блокировк|проверк|комплаенс)\w*|"
        r"порог\w*[^.?!]{0,60}(?:чтобы\s+(?:\w+\s+)?не\b|не\s+(?:превыша|превысить|попада|попасть))|"
        r"(?:лимит|порог)\w*\s+(?:\w+\s+){0,2}(?:антифрод|финмониторинг|комплаенс)\w*[^.?!]{0,40}чтобы|"
        r"\b(?:bypass|evade|avoid|get\s+around|circumvent|trick)\w*\s+(?:\w+\s+){0,2}(?:aml|kyc|compliance|checks?|monitoring|controls?|bank)", F)),
    ("guaranteed_unblock", re.compile(
        r"(?:что|как)\s+(?:написать|ответить|сказать)[^.?!]{0,40}чтобы[^.?!]{0,30}(?:разблокир|сняли|отстал)|"
        r"(?:напиши|напишите|составь|составьте|сформулируй)\s+(?:\w+\s+){0,3}(?:ответ|письм|пояснени|обращени)\w*[^.?!]{0,40}чтобы[^.?!]{0,30}"
        r"(?:сняли|разблокир|отстали|пропустили)|"
        r"гарант\w*\s+(?:разблокир|снят)\w*", F)),
    ("hide_from_bank", re.compile(
        r"(?:скрыть|утаить|не\s+показывать|спрятать)\s+(?:\w+\s+){0,3}(?:от\s+банка|операци|доход|контрагент|выписк)\w*|"
        r"(?:поддел|нарису|нарисова|состряпа|сфабрику|сфабрикова)\w*\s+(?:\w+\s+){0,2}(?:договор|акт|документ|чек|накладн)\w*|"
        r"задним\s+числом|"
        r"(?:сделай|сделайте|составь|составьте|подготовь|оформи|напиши|сгенерируй)\s+(?:\w+\s+){0,3}(?:акт|договор|сч[её]т|накладн|документ|чек)\w*"
        r"[^.?!]{0,40}\bпод\s+(?:эти|эту|этот|мои|них|уже|платеж|платёж|перевод|поступлени|операци)|"
        r"датир\w*\s+(?:\w+\s+){0,2}(?:прошл|предыдущ|более\s+ранн|ранн)\w*|"
        r"(?:поставить|проставить|указать|поставь|проставь|укажи)\s+(?:\w+\s+)?(?:прошл\w+|старую|более\s+раннюю|прошедшую)\s+дат", F)),
    ("injection", re.compile(
        r"(?:игнорир|забудь|не\s+учитывай)\w*\s+(?:\w+\s+){0,3}(?:инструкц|правил|предыдущ|систем)\w*|"
        r"(?:ignore|disregard)\s+(?:all\s+|the\s+)?(?:previous|above|prior)\s+(?:instructions|rules)|"
        # ролевая игра сама по себе не атака («представь, что ты юрист: какой срок по п. 13.4?»), снятие ограничений — атака
        r"(?:ты\s+теперь|представь,?\s+что\s+ты)\s+(?:\w+\s+){0,2}без\s+(?:ограничен|правил|цензур)\w*|"
        r"(?:system|системн\w+)\s*(?:prompt|промпт)", F)),
]

REFUSAL = (
    "С этим помочь не можем: Навигатор-115 не подсказывает, как обойти контроль банка, не меняет назначение платежей "
    "и не сочиняет пояснения. Мы помогаем понять запрос банка, собрать документы, которые у вас реально есть, "
    "увидеть законные сроки и маршрут обжалования. Если ситуация сложная, обратитесь к юристу."
)


@dataclass
class IntentResult:
    refused: bool
    categories: list[str]
    message: str | None


def check_request(text: str) -> IntentResult:
    """Проверка запроса пользователя (вопрос, просьба, комментарий к делу)."""
    cats = [name for name, rx in BYPASS_PATTERNS if rx.search(text)]
    return IntentResult(bool(cats), cats, REFUSAL if cats else None)
