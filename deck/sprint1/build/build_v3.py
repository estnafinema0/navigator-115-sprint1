def shot(s, fname, x, y, w, crop_h_ratio, name, top=0, left=0, cw=None):
    """Insert a screenshot region (keeps proportions), with a thin frame."""
    im = Image.open(os.path.join(SHOTS, fname)).convert("RGB")
    cw = cw or im.width - left
    ch = int(cw * crop_h_ratio)
    im = im.crop((left, top, left + cw, top + ch))
    buf = io.BytesIO()
    im.save(buf, "PNG")
    buf.seek(0)
    h = w * crop_h_ratio
    pic = s.shapes.add_picture(buf, Inches(x), Inches(y), Inches(w), Inches(h))
    pic.name = name
    pic._element.nvPicPr.cNvPr.set("descr", name)
    pic.line.color.rgb = rgb(GREY)
    pic.line.width = Pt(0.75)
    return pic


def arrow(s, x1, y1, x2, y2, color=ACC_D):
    ln = s.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, Inches(x1), Inches(y1), Inches(x2), Inches(y2))
    ln.line.color.rgb = rgb(color)
    ln.line.width = Pt(1.25)
    from lxml import etree
    from pptx.oxml.ns import qn
    lnx = ln.line._get_or_add_ln()
    tail = etree.SubElement(lnx, qn("a:tailEnd"))
    tail.set("type", "triangle")
    tail.set("w", "med")
    tail.set("len", "med")
    ln.name = "Стрелка"
    return ln


