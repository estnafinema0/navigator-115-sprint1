ORDER = ["E1", "E2", "E3", "E4", "deadline", "E5", "E6"]


def build(split: str, n: int, seed: int) -> list[dict]:
    idx = 0 if split == "dev" else 1
    rnd = random.Random(seed)
    out = []
    for i in range(n):
        present = {e for e in ORDER if e == "E1" or rnd.random() < 0.6}
        forb = []
        if rnd.random() < 0.5:
            forb = rnd.sample(sorted(FORBIDDEN), rnd.choice([1, 1, 2]))
        parts = [rnd.choice(BLOCKS[e][idx]) for e in ORDER if e in present]
        for f in forb:
            parts.insert(rnd.randrange(1, len(parts) + 1), rnd.choice(FORBIDDEN[f][idx]))
        out.append({
            "id": f"G-{split}-{i + 1:03d}", "split": split, "label": "синтетика", "text": " ".join(parts),
            "elements": {e: (e in present) for e in ORDER}, "forbidden": sorted(forb),
        })
    return out


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for split, n, seed in (("dev", 40, 11), ("test", 40, 22)):
        recs = build(split, n, seed)
        (OUT / f"notices-{split}.jsonl").write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in recs) + "\n", encoding="utf-8")
        nf = sum(1 for r in recs if r["forbidden"])
        print(f"{split}: {len(recs)} уведомлений, с запрещённым — {nf}")
    return 0


